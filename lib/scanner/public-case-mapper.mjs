export function toPublicScannerCase(record) {
  return {
    id: record.id,
    externalId: record.externalId,
    slug: record.slug,
    name: record.name,
    age: record.age,
    countryCode: record.countryCode,
    countryName: record.countryName,
    countrySlug: record.countrySlug,
    region: record.region,
    city: record.city,
    locationSlug: record.locationSlug,
    missingSince: record.missingSince,
    lastSeenLocationPublic: record.lastSeenLocationPublic,
    publicLatitude: record.publicLatitude,
    publicLongitude: record.publicLongitude,
    locationConfidence: record.locationConfidence,
    sourceName: record.sourceName,
    sourceUrl: record.sourceUrl,
    sourcePublishedAt: record.sourcePublishedAt,
    importedAt: record.importedAt,
    lastCheckedAt: record.lastCheckedAt,
    status: record.status,
    isPublic: Boolean(record.isPublic),
    caseType: 'missing-person',
    shortSummary: record.shortSummary,
    publicDescription: record.publicDescription || record.shortSummary,
    gender: record.gender,
    physicalDescription: record.physicalDescription,
    clothing: record.clothing,
    travelContext: record.travelContext,
    photoUrl: record.canShowPhotoWhileActive ? record.photoUrl : '',
    photoVisibility: record.canShowPhotoWhileActive ? 'public-active' : 'placeholder',
    tags: record.tags || [],
    contactInstruction: record.contactInstruction,
    duplicateKey: record.duplicateKey,
  }
}
